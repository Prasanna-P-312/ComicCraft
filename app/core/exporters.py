"""
PDF Exporter Module: Compiles multi-panel comic stories into professionally formatted PDF documents using FPDF.
Ensures perfect alignment of images, captions, narration, and character dialogues without overlapping.
"""
import os
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any
from fpdf import FPDF
from app.config import settings

class ComicPDF(FPDF):
    """Custom FPDF class for styling ComicCraft PDF books."""

    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 8, "COMICCRAFT  *  AI Comic Story Chronicles", align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(226, 232, 240)
        self.set_line_width(0.5)
        self.line(10, 16, 200, 16)
        self.ln(4)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by ComicCraft (AI Comic Story Creator)", align="C")

def _clean_text(text: str) -> str:
    """Replaces Unicode quotes and characters with ASCII equivalents for FPDF compatibility."""
    if not text:
        return ""
    replacements = {
        "\u2018": "'", "\u2019": "'",
        "\u201c": '"', "\u201d": '"',
        "\u2013": "-", "\u2014": "--",
        "\u2026": "...", "\u2022": "*",
        "\u00e9": "e", "\u00e8": "e",
        "\u00a0": " "
    }
    for orig, rep in replacements.items():
        text = text.replace(orig, rep)
    return text.encode("latin-1", "replace").decode("latin-1")

def save_pdf(layout: List[Dict[str, Any]], story_prompt: str, character_name: str, tone: str, art_style: str) -> Dict[str, str]:
    """
    Compiles comic panels into a multi-page PDF document.
    Dynamically positions every text element so that image, caption, narration, and dialogue
    never overlap regardless of length.
    """
    settings.EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    pdf_filename = f"comic_{timestamp}.pdf"
    pdf_path = settings.EXPORTS_DIR / pdf_filename

    pdf = ComicPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=False)  # Precise manual control over panel pages

    # ---------------- COVER PAGE ----------------
    pdf.add_page()
    pdf.ln(15)

    # Title Banner
    pdf.set_fill_color(15, 23, 42)
    pdf.rect(10, 30, 190, 42, "F")
    pdf.set_font("Helvetica", "B", 24)
    pdf.set_text_color(245, 197, 24)  # Comic Yellow
    pdf.set_y(36)
    pdf.cell(0, 12, "COMICCRAFT CHRONICLES", align="C", new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(241, 245, 249)
    pdf.cell(0, 8, _clean_text(f"An AI Comic Adventure Featuring {character_name}"), align="C", new_x="LMARGIN", new_y="NEXT")

    # Metadata Card
    pdf.set_fill_color(255, 255, 255)
    pdf.set_draw_color(15, 23, 42)
    pdf.set_line_width(0.8)
    pdf.rect(15, 85, 180, 85, "DF")

    pdf.set_y(90)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(170, 7, "  STORY SPECIFICATIONS", new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(245, 197, 24)
    pdf.set_line_width(1.0)
    pdf.line(20, 99, 190, 99)
    pdf.ln(5)

    fields = [
        ("Main Character:", character_name),
        ("Story Tone:", tone),
        ("Art Style:", art_style),
        ("Created At:", datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
    ]

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(71, 85, 105)
    pdf.set_x(20)
    pdf.cell(40, 6, "Story Premise:", new_x="RIGHT", new_y="TOP")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(15, 23, 42)
    pdf.multi_cell(125, 6, _clean_text(story_prompt))
    pdf.ln(2)

    for label, val in fields:
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(71, 85, 105)
        pdf.set_x(20)
        pdf.cell(40, 6, label, new_x="RIGHT", new_y="TOP")
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(125, 6, _clean_text(val), new_x="LMARGIN", new_y="NEXT")

    # ---------------- COMIC PANELS (1 per page) ----------------
    for panel in layout:
        pdf.add_page()
        p_num = panel.get("panel_number", 1)
        title = panel.get("title", f"Panel {p_num}")
        img_rel = panel.get("image_path", "")
        caption = panel.get("caption", "")
        narration = panel.get("narration", "")
        dialogue = panel.get("dialogue", "")

        # 1. Panel Header Bar (Top: y=20)
        pdf.set_fill_color(241, 245, 249)
        pdf.set_draw_color(15, 23, 42)
        pdf.set_line_width(0.7)
        pdf.rect(15, 20, 180, 11, "DF")

        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(15, 23, 42)
        pdf.set_y(22)
        pdf.set_x(20)
        pdf.cell(0, 7, _clean_text(f"PANEL {p_num}: {title}"), align="L", new_x="LMARGIN", new_y="NEXT")

        # 2. Panel Image (Centered: x=55, y=34, w=100, h=100)
        img_y = 34
        img_h = 100
        img_abs = settings.BASE_DIR / img_rel
        if img_abs.exists():
            pdf.image(str(img_abs), x=55, y=img_y, w=100, h=img_h)
            # Thin border around image
            pdf.set_draw_color(15, 23, 42)
            pdf.set_line_width(0.5)
            pdf.rect(55, img_y, 100, img_h)
        else:
            pdf.set_fill_color(241, 245, 249)
            pdf.rect(55, img_y, 100, img_h, "F")
            pdf.set_y(img_y + 45)
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(100, 116, 139)
            pdf.cell(0, 10, "[Illustration Rendered in Web Preview]", align="C", new_x="LMARGIN", new_y="NEXT")

        # 3. Content Boxes below image (starting at y=138)
        current_y = img_y + img_h + 5

        # 3a. Ambient Caption Box
        if caption:
            pdf.set_font("Helvetica", "BI", 9)
            cleaned_caption = _clean_text(f"[CAPTION] {caption}")
            pdf.set_fill_color(254, 243, 199)  # Light amber
            pdf.set_draw_color(245, 158, 11)   # Amber border
            pdf.set_line_width(0.5)
            pdf.rect(15, current_y, 180, 11, "DF")

            pdf.set_y(current_y + 2)
            pdf.set_x(18)
            pdf.set_text_color(146, 64, 14)
            pdf.cell(174, 7, cleaned_caption, new_x="LMARGIN", new_y="NEXT")
            current_y += 14

        # 3b. Narration Box
        if narration:
            pdf.set_font("Helvetica", "", 9.5)
            cleaned_narration = _clean_text(narration)
            
            # Estimate height based on character length
            lines_est = max(1, len(cleaned_narration) // 85 + 1)
            box_h = 10 + (lines_est * 5)

            pdf.set_fill_color(248, 250, 252)  # Light slate
            pdf.set_draw_color(203, 213, 225)
            pdf.set_line_width(0.5)
            pdf.rect(15, current_y, 180, box_h, "DF")

            pdf.set_y(current_y + 2)
            pdf.set_x(19)
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(100, 116, 139)
            pdf.cell(170, 4, "SCENE NARRATION", new_x="LMARGIN", new_y="NEXT")

            pdf.set_font("Helvetica", "", 9.5)
            pdf.set_text_color(15, 23, 42)
            pdf.set_x(19)
            pdf.multi_cell(172, 4.8, cleaned_narration)
            current_y += box_h + 3

        # 3c. Dialogue Speech Bubble
        if dialogue:
            cleaned_dialogue = _clean_text(dialogue)
            lines_dlg = max(1, len(cleaned_dialogue) // 85 + 1)
            dlg_box_h = 10 + (lines_dlg * 5)

            pdf.set_fill_color(236, 253, 245)  # Light emerald
            pdf.set_draw_color(16, 185, 129)   # Emerald border
            pdf.set_line_width(0.5)
            pdf.rect(15, current_y, 180, dlg_box_h, "DF")

            pdf.set_y(current_y + 2)
            pdf.set_x(19)
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(5, 150, 105)
            pdf.cell(170, 4, "CHARACTER DIALOGUE", new_x="LMARGIN", new_y="NEXT")

            pdf.set_font("Helvetica", "I", 9.5)
            pdf.set_text_color(6, 78, 59)
            pdf.set_x(19)
            pdf.multi_cell(172, 4.8, cleaned_dialogue)

    pdf.output(str(pdf_path))
    return {
        "filename": pdf_filename,
        "filepath": str(pdf_path),
        "download_url": f"/download-pdf/{pdf_filename}"
    }
